BEGIN;
CREATE TABLE IF NOT EXISTS public.hongfa_library_book_map (
    library_item_id bigint PRIMARY KEY REFERENCES public.library_items(id),
    hongfa_item_id bigint NOT NULL UNIQUE REFERENCES public.hongfa_items(id),
    item_code text NOT NULL,
    book_name text NOT NULL,
    category text,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.hongfa_library_transfers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_key uuid NOT NULL,
    team_id bigint NOT NULL REFERENCES public.hongfa_teams(id),
    library_item_id bigint NOT NULL REFERENCES public.hongfa_library_book_map(library_item_id),
    item_code text NOT NULL,
    book_name text NOT NULL,
    category text,
    quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 100000),
    received_by text NOT NULL,
    received_at timestamptz NOT NULL DEFAULT now(),
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed')),
    confirmed_by text,
    confirmed_at timestamptz,
    library_transaction_id bigint UNIQUE REFERENCES public.library_transactions(id),
    UNIQUE (request_key, library_item_id),
    CHECK ((status = 'pending' AND confirmed_by IS NULL AND confirmed_at IS NULL AND library_transaction_id IS NULL)
        OR (status = 'confirmed' AND confirmed_by IS NOT NULL AND confirmed_at IS NOT NULL AND library_transaction_id IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS hongfa_library_pending_idx
    ON public.hongfa_library_transfers(library_item_id) WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS hongfa_library_team_history_idx
    ON public.hongfa_library_transfers(team_id, received_at DESC, id DESC);
ALTER TABLE public.hongfa_library_book_map ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.hongfa_library_transfers ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.hongfa_library_book_map, public.hongfa_library_transfers FROM anon, authenticated;

-- Concurrent legacy outflows cannot use already reserved stock. No change
-- for items without pending transfers. The original Excel handler is intact.
CREATE OR REPLACE FUNCTION public.hongfa_library_protect_reserved() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
DECLARE pending bigint;
BEGIN
    IF NEW.balance IS NOT DISTINCT FROM OLD.balance THEN
        RETURN NEW;
    END IF;
    SELECT SUM(quantity) INTO pending FROM public.hongfa_library_transfers
        WHERE library_item_id = OLD.id AND status = 'pending';
    IF pending IS NOT NULL AND (NEW.balance IS NULL OR NEW.balance < pending) THEN
        RAISE EXCEPTION '藏经阁库存包含弘法待确认领取，请先核对领取记录' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS hongfa_library_protect_reserved ON public.library_items;
CREATE TRIGGER hongfa_library_protect_reserved BEFORE UPDATE OF balance ON public.library_items
    FOR EACH ROW EXECUTE FUNCTION public.hongfa_library_protect_reserved();

-- The legacy cancel endpoint must not reverse only the library half.
CREATE OR REPLACE FUNCTION public.hongfa_library_protect_transaction() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM public.hongfa_library_transfers WHERE library_transaction_id = OLD.id) THEN
        RAISE EXCEPTION '弘法领取出库须由两边负责人对账，不可单独取消' USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS hongfa_library_protect_transaction ON public.library_transactions;
CREATE TRIGGER hongfa_library_protect_transaction BEFORE UPDATE OR DELETE ON public.library_transactions
    FOR EACH ROW EXECUTE FUNCTION public.hongfa_library_protect_transaction();
COMMIT;
